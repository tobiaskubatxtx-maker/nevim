"""Run with an active Vite server: python tests/e2e.py (requires Playwright + Chromium)."""
import os, shutil
from playwright.sync_api import sync_playwright,expect
with sync_playwright() as p:
 browser=p.chromium.launch(executable_path=os.environ.get('CHROMIUM_PATH') or shutil.which('chromium'),headless=True,args=['--no-sandbox','--disable-dev-shm-usage'],timeout=20000)
 page=browser.new_page(viewport={'width':1440,'height':1000})
 errors=[]
 page.on('pageerror',lambda e:errors.append(str(e)))
 page.goto(os.environ.get('BASE_URL','http://127.0.0.1:5173/'),wait_until='domcontentloaded')
 expect(page.get_by_role('heading',name='Dobrý den, Anno.')).to_be_visible()
 page.get_by_role('button',name='Nová rezervace',exact=True).click()
 dialog=page.get_by_role('dialog')
 dialog.get_by_label('Od',exact=True).fill('09:30')
 dialog.get_by_label('Do',exact=True).fill('10:30')
 dialog.get_by_role('button',name='Uložit rezervaci').click()
 expect(dialog.get_by_role('alert')).to_contain_text('překrývá')
 dialog.get_by_label('Od',exact=True).fill('10:00')
 dialog.get_by_label('Do',exact=True).fill('11:00')
 dialog.get_by_label('Poznámka').fill('Test tréninku')
 dialog.get_by_role('button',name='Uložit rezervaci').click()
 expect(dialog).not_to_be_visible()
 page.locator('nav').get_by_role('button',name='Moje rezervace').click()
 expect(page.locator('.booking-row')).to_have_count(3)
 page.locator('.booking-row').filter(has_text='10:00–11:00').click()
 dialog.get_by_role('button',name='Upravit',exact=True).click()
 dialog.get_by_label('Od',exact=True).fill('17:00')
 dialog.get_by_label('Do',exact=True).fill('18:00')
 dialog.get_by_role('button',name='Uložit rezervaci').click()
 expect(page.locator('.booking-row').filter(has_text='17:00–18:00')).to_have_count(1)
 page.locator('.booking-row').filter(has_text='17:00–18:00').click()
 dialog.get_by_role('button',name='Zrušit termín',exact=True).click()
 dialog.get_by_role('button',name='Ano, zrušit rezervaci').click()
 expect(page.locator('.booking-row')).to_have_count(2)
 page.locator('nav').get_by_role('button',name='Rezervace',exact=True).click()
 page.get_by_role('button',name='Týden',exact=True).click()
 expect(page.locator('.day-column')).to_have_count(7)
 page.get_by_role('button',name='Den',exact=True).click()
 page.locator('.calendar-event').filter(has_text='Petr Dvořák').click()
 expect(dialog.get_by_role('button',name='Upravit',exact=True)).to_have_count(0)
 dialog.get_by_role('button',name='Zavřít',exact=True).click()
 page.locator('#demo-user').select_option('admin')
 page.locator('nav').get_by_role('button',name='Administrace',exact=True).click()
 page.locator('.admin-area').first.get_by_role('button',name='Dočasně uzavřít').click()
 expect(page.locator('.admin-area').first).to_contain_text('Plocha je uzavřená')
 page.locator('nav').get_by_role('button',name='Rezervace',exact=True).click()
 expect(page.get_by_role('heading',name='Plocha je dočasně uzavřená')).to_be_visible()
 page.locator('nav').get_by_role('button',name='Administrace',exact=True).click()
 page.locator('.admin-area').first.get_by_role('button',name='Znovu otevřít').click()
 page.get_by_role('button',name='Rezervace a blokace',exact=True).click()
 page.get_by_role('button',name='Blokovat termín').click()
 dialog.get_by_label('Od',exact=True).fill('18:00')
 dialog.get_by_label('Do',exact=True).fill('19:00')
 dialog.get_by_role('button',name='Uložit rezervaci').click()
 expect(page.locator('.admin-booking')).to_have_count(7)
 page.get_by_role('button',name='Uživatelé',exact=True).click()
 page.get_by_label('Jméno nového uživatele').fill('Eva Testovací')
 page.get_by_role('button',name='Přidat do ukázky').click()
 expect(page.locator('.user-row')).to_have_count(5)
 page.locator('nav').get_by_role('button',name='Provozní řád',exact=True).click()
 page.get_by_label('Pravidla rezervací',exact=True).fill('Návrh testovaného pravidla')
 page.locator('#demo-user').select_option('anna')
 page.locator('nav').get_by_role('button',name='Provozní řád',exact=True).click()
 expect(page.get_by_text('Návrh testovaného pravidla',exact=True)).to_be_visible()
 expect(page.locator('nav').get_by_role('button',name='Administrace')).to_have_count(0)
 page.reload(wait_until='domcontentloaded')
 expect(page.get_by_role('heading',name='Dobrý den, Anno.')).to_be_visible()
 print('PASS: create, collision, adjacency, edit, cancel, weekly view, ownership, closure, admin blocking, users, rules and demo reset',flush=True)
 page.set_viewport_size({'width':390,'height':844})
 expect(page.get_by_role('heading',name='Dobrý den, Anno.')).to_be_visible()
 assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth'), 'mobile overflow'
 page.get_by_role('button',name='Otevřít navigaci').click()
 page.locator('nav').get_by_role('button',name='Rezervace',exact=True).click()
 expect(page.get_by_role('heading',name='Kalendář rezervací')).to_be_visible()
 page.get_by_role('button',name='Nová rezervace',exact=True).click()
 expect(dialog).to_be_visible()
 assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth'), 'modal overflow'
 dialog.get_by_role('button',name='Zavřít dialog').click()
 page.screenshot(path='/tmp/jk-mobile.png',full_page=True)
 assert not errors, errors
 print('PASS: 390px mobile navigation, booking dialog and no JS errors',flush=True)
 browser.close()
